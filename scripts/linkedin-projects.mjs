// Generates the LinkedIn "Projects" entries from the registry + EN content (one per storefront,
// product and personal project), in the profile's standard anatomy:
//   summary line → bullets → Stack line → Live/Dev line.
// Run with bun (imports the TS sources): bun scripts/linkedin-projects.mjs
// Output: docs/linkedin/2026-09-projects.json (driver input) + .md (readable).
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { stores, products, personalProjects } from '../src/data/registry.ts'
import { en } from '../src/content/en.ts'

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
const fmt = (ym) => { const [y, m] = ym.split('-'); return `${MONTHS[Number(m) - 1]} ${y}` }
const gallery = (slug) => resolve('public/gallery', slug, 'linkedin.webp')
const projects = []

// LinkedIn skills must come from its taxonomy; map the stack chips onto standard names.
const SKILL_MAP = [
  [/shopify/i, 'Shopify'], [/liquid/i, 'Liquid'], [/react/i, 'React.js'], [/remix/i, 'Remix'], [/tailwind/i, 'Tailwind CSS'],
  [/next/i, 'Next.js'], [/django/i, 'Django'], [/postgres|neon/i, 'PostgreSQL'], [/typescript/i, 'TypeScript'], [/wordpress/i, 'WordPress'],
  [/astro/i, 'Astro'], [/a\/b/i, 'A/B Testing'], [/klaviyo/i, 'Klaviyo'], [/vite/i, 'Vite'], [/three/i, 'Three.js'], [/framer/i, 'Framer'],
  [/woocommerce/i, 'WooCommerce'], [/prisma/i, 'Prisma'], [/functions|wasm/i, 'WebAssembly'], [/pixel|track|events/i, 'Web Analytics'],
  [/quiz|offers|bundle|reviews|pricing|sync/i, 'E-commerce'], [/ocr/i, 'OCR'], [/extension/i, 'Browser Extensions'], [/ai sdk/i, 'Generative AI'],
]
const skillsFor = (stack, base = []) => {
  const out = [...base]
  for (const chip of stack) for (const [re, name] of SKILL_MAP) if (re.test(chip) && !out.includes(name)) { out.push(name); break }
  return out.slice(0, 3)
}
// The CTO position starts Jun 2024; anything earlier belongs to the 2023-24 Shopify developer role.
const roleFor = (start) => (start >= '2024-06' ? 'cto' : 'fe2023')

for (const st of stores) {
  const c = en.stores[st.slug] ?? {}
  const facts = st.facts.map((f) => `• ${c.factLabels?.[f.id] ?? f.id}: ${f.value}`)
  const lines = [
    c.tagline ?? '',
    '',
    c.description ?? '',
    ...(facts.length ? ['', ...facts] : []),
    '',
    `Stack: ${st.stack.join(', ')}`,
    st.status === 'live' ? (st.url ? `Live: ${st.url.replace(/^https?:\/\/(www\.)?/, '')}` : 'Live (client store).') : 'In development — captured from the DEV theme; the client\'s current theme stays live until launch.',
  ]
  projects.push({
    key: st.slug,
    kind: 'store',
    name: `${st.name} — Shopify storefront`,
    description: lines.join('\n').trim(),
    start: st.timeline.start,
    end: st.status === 'live' ? st.timeline.end : null, // dev builds: "currently working on"
    associated: roleFor(st.timeline.start),
    skills: skillsFor(st.stack, ['Shopify', 'Liquid']),
    media: st.gallery ? gallery(st.slug) : null,
    url: st.url || null,
  })
}

for (const p of products) {
  const c = en.products[p.id] ?? {}
  projects.push({
    key: p.id,
    kind: 'product',
    name: `${p.name} — Digitdeck`,
    description: [c.tagline ?? '', '', c.description ?? '', '', `Stack: ${p.stack.join(', ')}`, p.url ? `Live: ${p.url.replace(/^https?:\/\/(www\.)?/, '')}` : ''].join('\n').trim(),
    start: `${p.year}`,
    end: null,
    associated: 'cto',
    skills: skillsFor(p.stack),
    media: p.gallery ? gallery(p.id) : null,
    url: p.url || null,
  })
}

for (const p of personalProjects) {
  const c = en.projects[p.id] ?? {}
  projects.push({
    key: p.id,
    kind: 'personal',
    name: p.name,
    description: [c.tagline ?? '', '', c.description ?? '', '', `Stack: ${p.stack.join(', ')}`, p.url ? `Live: ${p.url.replace(/^https?:\/\/(www\.)?/, '')}` : '', p.repo ? `Code: ${p.repo.replace(/^https?:\/\//, '')}` : ''].filter((l, i, a) => !(l === '' && a[i - 1] === '')).join('\n').trim(),
    start: `${p.year}`,
    end: null,
    associated: 'none',
    skills: skillsFor(p.stack),
    media: null,
    url: p.url || p.repo || null,
  })
}

writeFileSync('docs/linkedin/2026-09-projects.json', JSON.stringify(projects, null, 2) + '\n')
const md = ['# LinkedIn — Projects (September 2026)', '', 'Generated by `scripts/linkedin-projects.mjs` from the registry + EN content. One entry per storefront, product and personal project; same anatomy as the experience entries.', '']
for (const p of projects) md.push(`## ${p.name}`, '', `- ${fmt(p.start.length === 4 ? p.start + '-01' : p.start).replace(/^Jan (\d{4})$/, (m, y) => (p.start.length === 4 ? y : m))} – ${p.end ? fmt(p.end) : 'Present'} · associated: ${p.associated} · skills: ${p.skills.join(', ')}${p.media ? ' · media ✓' : ''}`, '', p.description, '')
writeFileSync('docs/linkedin/2026-09-projects.md', md.join('\n'))
console.log(projects.length, 'projects;', projects.filter((p) => p.media).length, 'with media')
